"""
(1) 생각 모드(thinking) on/off — Qwen 2.5 에는 없던 기능.
Qwen 3.5 는 같은 모델 안에서 "깊게 생각하고 답하기"와 "바로 답하기"를 전환할 수 있다.
호출 방법은 ollama.chat() 에 think=True/False 인자 하나만 추가하면 된다.

준비: pip install ollama  +  ollama pull qwen3.5:2b
"""
import ollama

MODEL = "qwen3.5:2b"


def ask(question: str, think: bool, **options):
    resp = ollama.chat(model=MODEL, messages=[{"role": "user", "content": question}],
                        think=think, options=options)
    return resp


# ── 기본 사용법 — 옵션 없이 think=True/False 만 ────────────────
print("[생각 모드 OFF]")
r_off = ask("인공지능을 한 문장으로 설명해줘.", think=False)
print(r_off["message"].content)

print("\n[생각 모드 ON]")
r_on = ask("인공지능을 한 문장으로 설명해줘.", think=True)
thinking = r_on["message"].thinking or ""
print(f"[내부 사고 과정] ({len(thinking)}자 전체)")
print(thinking)
print("\n[최종 답변]")
print(r_on["message"].content)


# 정리:
#   - 켜고 끄는 건 think=True/False 한 줄이 전부다. Qwen 2.5(../5.qwen25)에는 이 옵션 자체가
#     없다 — think 인자를 줘도 무시되고 그냥 바로 답한다.
#   - 생각 모드를 켜면 답하기 전에 내부 사고 과정(message["thinking"])을 먼저 만든다. 그만큼
#     시간이 더 걸린다(아래 CPU 실측: OFF 2초 vs ON 53초 — 26배 차이).
#   - 같은 모델 파일 하나로 이 둘을 다 한다 — Qwen 2.5→3.5처럼 "버전을 통째로 바꾸는" 게
#     아니라 매 호출마다 옵션으로 켜고 끌 수 있다는 게 하이브리드 사고 모드의 핵심이다.


# ─── 실행 결과 (실측, qwen3.5:2b, CPU) ───────────────────────────
# [생각 모드 OFF]  (2.0초)
# 이전 지식에 기반하여 예측과 행동을 수행할 수 있는 지능형 알고리즘입니다.
#
# [생각 모드 ON]  (52.7초)
# (내부 사고 과정 6055자를 먼저 만든 뒤 아래를 답했다)
# 데이터나 상황을 분석·학습하며 자동으로 의사결정을 내리고 인간이 수행하지 않는 작업을
# 대체할 수 있는 시스템 기술입니다.
#
# → 매 실행마다 문장은 조금씩 달라지지만(샘플링 특성), OFF는 항상 훨씬 빠르고(수 초),
#   ON은 사고 과정을 거치느라 수십 초가 걸린다는 경향은 재현된다.


# ─── 참고: 같은 실험을 GPU 서버(RTX 4070 Laptop, 8GB VRAM)에서 실측 ────────
# [생각 모드 OFF]   7.5초  (첫 호출 — 모델을 VRAM에 올리는 로딩 비용 포함)
# [생각 모드 ON]    31.0초  (사고 과정 7859자)
#   → CPU 대비 ON은 확실히 빠르다(53초→31초, 약 1.7배). 반면 OFF가 CPU(2초)보다 느리게
#     찍힌 건 GPU가 느려서가 아니라 "그 호출에서 모델을 처음 로딩"했기 때문이다 — 같은 모델을
#     연속으로 부르면 이미 올라가 있어서 그 다음부터는 훨씬 빨라진다(아래 tool calling
#     실측에서 첫 호출 7.5초 vs 이후 호출 0.7~1.4초로 확인된다).


# ══════════════════════════════════════════════════════════════
# 심화 — 생각 모드는 "예산(토큰 한도)"을 잘못 잡으면 답을 아예 못 낼 수도 있다
# ══════════════════════════════════════════════════════════════
# 위처럼 평범한 질문은 옵션 없이도 잘 되지만, 아래처럼 아주 사소한 산수 문제에서는 이 모델이
# 유독 "생각"을 과도하게 길게 하다가 num_predict(한 번에 생성 가능한 최대 토큰 수) 예산을
# 사고 과정만으로 다 써버리는 경우가 실측된다 — 그러면 최종 답은 한 글자도 못 쓰고 끝난다.

QUESTION2 = "17 더하기 26은 얼마인가? 한 문장으로만 답하라."

print("\n\n[심화] 예산을 적게 주면(1024 토큰) — 사고만 하다가 끝날 수 있다")
r_small = ask(QUESTION2, think=True, num_predict=1024)
print(f"  done_reason={r_small.get('done_reason')}, 생성한 토큰 수={r_small.get('eval_count')}")
print(f"  답: {r_small['message'].content!r}")

print("\n[심화] 예산을 넉넉히 주면(3000 토큰) — 사고를 끝내고 답까지 낸다")
r_big = ask(QUESTION2, think=True, num_predict=3000)
print(f"  done_reason={r_big.get('done_reason')}, 생성한 토큰 수={r_big.get('eval_count')}, "
      f"사고 과정 길이={len(r_big['message'].thinking or '')}자")
print(f"  답: {r_big['message'].content}")


# 정리(심화):
#   - 생각 모드의 "사고 과정"과 "최종 답"은 같은 토큰 예산 안에서 순서대로 소비된다 — 사고가
#     길어지면 정작 답을 쓸 자리가 안 남을 수 있다(done_reason=length 가 그 증거).
#   - 실전에서 생각 모드를 켤 땐 num_predict/max_tokens 를 충분히 넉넉하게 잡아야 한다 —
#     그렇지 않으면 "생각만 하다가 끝난" 빈 답변을 받게 된다.
#   - **"3000이면 충분하다"도 아니다** — 아래 GPU 실측처럼 같은 3000 예산으로도 실행마다
#     사고 길이가 달라져서(샘플링) 어떤 실행에선 성공하고 어떤 실행에선 또 예산을 다 써버린다.
#     즉 안전한 고정값은 없다 — 실전에서는 "생각 전용 예산"과 "답변 전용 예산"을 분리해서
#     받거나(모델/도구가 지원하면), 실패 시 예산을 늘려 재시도하는 로직이 필요하다.


# ─── 실행 결과 (실측, qwen3.5:2b, CPU) ───────────────────────────
# [심화] 예산을 적게 주면(1024 토큰) — 사고만 하다가 끝날 수 있다
#   done_reason=length, 생성한 토큰 수=1024
#   답: ''
#
# [심화] 예산을 넉넉히 주면(3000 토큰) — 사고를 끝내고 답까지 낸다
#   done_reason=stop, 생성한 토큰 수=1740, 사고 과정 길이=5149자
#   답: 17 와 26 을 더한 합계가 되는结果是 43 이고요
#   (정답은 맞혔다 — 다만 작은 모델이라 한자가 섞여 나오는 등 문장이 매끈하진 않다)


# ─── 참고: 같은 실험을 GPU 서버(RTX 4070 Laptop)에서 실측 ────────────────
# 1024토큰   13.5초  done_reason=length  답: ''            (CPU와 동일하게 실패)
# 3000토큰   39.0초  done_reason=length  답: ''            (← CPU에서는 성공했던 예산인데
#                                                              GPU에서는 이번엔 실패!)
#   → 하드웨어 차이가 아니라 매 실행마다 "얼마나 오래 생각할지"가 확률적으로 달라지기
#     때문이다. 같은 코드, 같은 예산이라도 성공/실패가 갈릴 수 있다는 걸 두 환경에서
#     교차 확인한 셈이다 — 이게 위 "정리(심화)"에서 강조하는 핵심이다.
#
# 5000토큰으로 다시 시도하면(CPU) 68.9초 만에 성공한다(done_reason=stop, 답 "43"). 그런데
# 내부 사고 과정을 전부 열어보면 왜 이렇게 오래 걸렸는지 드러난다 — **계산 자체는 셋째 줄에서
# 이미 끝났다**:
#
#     2. Evaluate the Math:
#        17 + 26
#        Calculation: 10+20=30, 7+6=13. Total = 43.
#
#   그런데 정답을 이미 구해놓고도 그 뒤로 "혹시 말장난 아닐까?", "숫자 자릿수 퍼즐인가?",
#   "시간 계산을 묻는 건가?", "한글 발음 수수께끼인가?", "혹시 중국어 질문인가?" 같은
#   자기 의심을 거의 100줄 가까이 반복하다가(같은 결론에 도달했다가 또 의심하고, 또
#   도달했다가 또 의심) 맨 마지막에야 실제로 답을 적는다. **"예산 부족"의 진짜 원인은
#   계산이 어려워서가 아니라 이런 불필요한 자기검열 루프가 예산을 다 잡아먹기 때문**이다 —
#   작은 모델일수록 "언제 생각을 멈춰야 할지" 판단이 서툴다는 뜻이다.
